"""Export the geography the offline forms need as a bundled TypeScript seed.

Run from apps/backend:  .venv/bin/python scripts/export_region_seed.py

Writes apps/mobile-expo/src/data/region-seed.ts so the mobile registration
forms can populate the state / district / village selects with zero network -
a phone that has never synced still gets real dropdown data.

States and districts are always exported in full (83 KB together). Villages
are scoped to a district list - the full national set is 652k rows (~82 MB
JSON), which cannot ship inside an app binary. The default list is the
deployment's districts; override with --districts a,b,c or use --all if the
size is acceptable. Regenerate whenever the deployment's catchment data
changes.
"""

import argparse
import asyncio
import json
import os
import re
import sys

import asyncpg

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUTPUT = os.path.join(REPO_ROOT, "apps", "mobile-expo", "src", "data", "region-seed.ts")

# Districts the forms offer offline. Mumbai is intentionally absent: the geo
# dataset has no Mumbai district (34 Maharashtra districts, checked).
DEFAULT_DISTRICTS = [
    "Kolhapur",
    "Chandrapur",
    "Nagpur",
    "Sangli",
    "Pune",
    "Satara",
]

VILLAGES_BY_DISTRICT = """
    SELECT v.id, v.name, d.id AS district_id
      FROM villages v
      JOIN sub_centers sc ON sc.id = v.sub_center_id
      JOIN phcs p ON p.id = sc.phc_id
      JOIN blocks b ON b.id = p.block_id
      JOIN districts d ON d.id = b.district_id
     WHERE lower(d.name) = ANY($1)
     ORDER BY v.name
"""

VILLAGES_ALL = """
    SELECT v.id, v.name, d.id AS district_id
      FROM villages v
      JOIN sub_centers sc ON sc.id = v.sub_center_id
      JOIN phcs p ON p.id = sc.phc_id
      JOIN blocks b ON b.id = p.block_id
      JOIN districts d ON d.id = b.district_id
     ORDER BY v.name
"""


def database_url() -> str:
    env_path = os.path.join(os.path.dirname(__file__), "..", ".env")
    with open(env_path) as handle:
        for line in handle:
            if line.startswith("DATABASE_URL="):
                return re.sub(r"\+[a-z]+://", "://", line.split("=", 1)[1].strip())
    raise SystemExit("DATABASE_URL not found in apps/backend/.env")


async def main(districts: list[str] | None, all_villages: bool) -> None:
    conn = await asyncpg.connect(database_url().replace("?ssl=require", ""), ssl="require")
    try:
        states = await conn.fetch("SELECT id, name FROM states ORDER BY name")
        districts_rows = await conn.fetch("SELECT id, name, state_id FROM districts ORDER BY name")
        if all_villages:
            villages = await conn.fetch(VILLAGES_ALL)
        else:
            wanted = [name.lower() for name in (districts or DEFAULT_DISTRICTS)]
            villages = await conn.fetch(VILLAGES_BY_DISTRICT, wanted)
    finally:
        await conn.close()

    seed = {
        "states": [dict(row) for row in states],
        "districts": [dict(row) for row in districts_rows],
        "villages": [dict(row) for row in villages],
    }
    body = json.dumps(seed, ensure_ascii=False, indent=0)
    header = (
        "// Generated by apps/backend/scripts/export_region_seed.py - do not edit by hand.\n"
        "// Bundled geography for the offline registration forms; regenerate after\n"
        "// changing the deployment's catchment data.\n"
    )
    with open(OUTPUT, "w") as handle:  # noqa: ASYNC230
        handle.write(header)
        handle.write("export interface RegionSeedPlace {\n  id: string;\n  name: string;\n}\n\n")
        handle.write("export interface RegionSeedDistrict extends RegionSeedPlace {\n  state_id: string;\n}\n\n")
        handle.write("export interface RegionSeedVillage extends RegionSeedPlace {\n  district_id: string;\n}\n\n")
        handle.write("export interface RegionSeed {\n")
        handle.write("  states: RegionSeedPlace[];\n")
        handle.write("  districts: RegionSeedDistrict[];\n")
        handle.write("  villages: RegionSeedVillage[];\n")
        handle.write("}\n\n")
        handle.write(f"export const REGION_SEED: RegionSeed = {body};\n")

    size = os.path.getsize(OUTPUT)  # noqa: ASYNC240
    print(
        f"Wrote {OUTPUT}\n"
        f"  states: {len(states)}  districts: {len(districts_rows)}  "
        f"villages: {len(villages)}  file: {size / 1024:.0f} KB"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all", action="store_true", help="export every village (~82 MB)")
    parser.add_argument(
        "--districts",
        help="comma-separated district names for the village scope "
        f"(default: {', '.join(DEFAULT_DISTRICTS)})",
    )
    args = parser.parse_args()
    wanted = [name.strip() for name in args.districts.split(",")] if args.districts else None
    sys.exit(asyncio.run(main(wanted, args.all)))
